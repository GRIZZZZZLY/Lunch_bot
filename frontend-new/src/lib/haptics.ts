/* ROCKET LUNCH — тактильная отдача Telegram Mini App.

   Зачем слой, а не прямые вызовы `window.Telegram.WebApp.HapticFeedback`:

   1. Метод есть не везде. Приложение открывается и в браузере (там объекта
      Telegram нет вовсе), и в старых клиентах, где `HapticFeedback` появился
      позже текущей версии Bot API — такой клиент на неизвестный метод бросает
      исключение, а не молчит. Необработанное оно уронило бы обработчик клика
      вместе с самим действием: тап по «Проголосовать» перестал бы голосовать.
      Поэтому каждый вызов обёрнут, и отсутствие вибрации остаётся отсутствием
      вибрации, а не сломанной кнопкой.

   2. Словарь фиксирован в одном месте. Три жеста продукта — «нажал»,
      «переключил», «получилось / не получилось» — и ровно три функции. Без
      этого выбор силы удара расходится по файлам, и одинаковые по смыслу
      действия отдают по-разному.

   Тактильная отдача НЕ подчиняется `prefers-reduced-motion`: настройка убирает
   движение, а не обратную связь (см. «Правило сохранённой обратной связи» в
   DESIGN.md). Вибрация ничего не двигает на экране и остаётся единственным
   каналом подтверждения там, где анимации выключены. */

type ImpactStyle = 'light' | 'medium' | 'heavy' | 'rigid' | 'soft';

function haptics() {
  return typeof window === 'undefined' ? undefined : window.Telegram?.WebApp?.HapticFeedback;
}

/** Нажатие принято: кнопки, строки списка, отправка голоса. */
export function hapticImpact(style: ImpactStyle = 'light'): void {
  try {
    haptics()?.impactOccurred(style);
  } catch {
    // клиент не умеет этот метод — тихо обходимся без вибрации
  }
}

/** Выбор изменился: чипы, вкладки, переключатели, чекбоксы. */
export function hapticSelection(): void {
  try {
    haptics()?.selectionChanged();
  } catch {
    // см. выше
  }
}

/** Исход операции. Идёт вместе с тостом, а не вместо него. */
export function hapticNotify(type: 'success' | 'error' | 'warning'): void {
  try {
    haptics()?.notificationOccurred(type);
  } catch {
    // см. выше
  }
}
