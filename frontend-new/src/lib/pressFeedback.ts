/* ROCKET LUNCH — включение `:active` на тач-экранах.

   DESIGN.md объявляет `:active` единственным каналом обратной связи под
   пальцем: hover на тач-экране залипает, поэтому «Правило hover только для
   указателя» запирает его в `@media (hover: hover)`, а всё подтверждение
   нажатия отдано `:active` — `scale(0.97)` у кнопки, `0.96` у чипа, `0.99` у
   строки блюда.

   В WebKit это правило работает не всегда. Движок применяет `:active` к
   произвольным элементам по касанию только если документ показал, что тач его
   интересует, — а признаком служит зарегистрированный обработчик тач-события.
   Без него нажатие подсвечивает в лучшем случае ссылки и кнопки, и то не в
   каждой версии. Mini App живёт в WebView iOS, то есть ровно в этом движке:
   вся тактильная часть визуального языка там могла не играть вовсе, и
   интерфейс отвечал на касание только конечным результатом.

   Слушатель намеренно пустой — важен факт регистрации, а не тело. `passive`
   обязателен: непассивный слушатель на `touchstart` заставляет движок ждать
   возможного `preventDefault` перед прокруткой, и лечение press-состояний
   стоило бы плавности скролла. */
export function enableTouchActiveStates(): void {
  if (typeof document === 'undefined') return;
  document.addEventListener('touchstart', () => {}, { passive: true });
}
