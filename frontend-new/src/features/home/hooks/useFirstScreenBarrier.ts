/**
 * Барьер первого экрана: открыть главную целиком или не открывать вовсе.
 *
 * Запись с телефона показала четыре отдельных проявления за 280ms: заголовок,
 * приветствие с карточкой «Сейчас», талон рывком, и уже внутри «Сейчас» —
 * строка победителя. Каждое было честным ответом своего запроса, но человек
 * видит не запросы, а как экран собирается четырьмя толчками.
 *
 * «Приехало» — это `isSuccess` или `isError`, а не наличие `data`. Первая
 * редакция смотрела на `data !== undefined` и открывала барьер сразу:
 * `useActivePoll` нормализует ответ в `q.data?.[0] ?? null`, то есть отдаёт null
 * вместо undefined ещё во время загрузки. Зонд это и показал — приветствие с
 * «Сейчас» проступали за 130ms до талона.
 *
 * `isLoading` здесь тоже не годится: у цепочки «последний опрос → его результат»
 * есть кадр, где ни один запрос не помечен загружающимся, и барьер открылся бы
 * в него. Ошибка считается ответом — экран, ждущий упавший запрос, не откроется
 * никогда. Отключённый запрос не «приехал», поэтому ожидаемость зависимых
 * спрашивается отдельно (см. `expected` у вызывающего), а от вечного ожидания
 * страхует потолок ниже.
 *
 * ВАЖНО при любой дальнейшей правке: хук принимает ОБЪЕКТЫ запросов, а не
 * распакованные данные. Распаковка теряет ровно то, на чём барьер и держится, —
 * различие «ответ получен» и «данные есть».
 */
import { useEffect, useState } from 'react';

/** Минимум, который барьеру нужен от запроса. */
export interface BarrierQuery {
  isSuccess: boolean;
  isError: boolean;
}

/** Потолок ожидания. Больше — экран выглядит зависшим. */
const BARRIER_CAP_MS = 1500;

export interface FirstScreenBarrier {
  /** Экран можно показывать: либо всё приехало, либо сработал потолок. */
  revealed: boolean;
  /** Экран действительно ждал данные — только тогда нужен каскад раскрытия. */
  waitedForData: boolean;
}

export function arrived(query: BarrierQuery): boolean {
  return query.isSuccess || query.isError;
}

export function useFirstScreenBarrier(ready: boolean): FirstScreenBarrier {
  /* Предохранитель: барьер без потолка — это риск вечного скелета. Достаточно
     одного запроса, выключенного по причине, которой мы здесь не знаем (нет
     группы, чужой сценарий), чтобы экран не открылся никогда. */
  const [capReached, setCapReached] = useState(false);
  useEffect(() => {
    const timer = window.setTimeout(() => setCapReached(true), BARRIER_CAP_MS);
    return () => window.clearTimeout(timer);
  }, []);

  /* Каскад раскрытия ставим только если экран действительно ждал данные. Тёплый
     кэш отдаёт всё на первом же рендере — раскрывать нечего, и приход в этом
     случае несёт сборка кадра (холодный старт) или переход между страницами.
     Так каскад с ними никогда не накладывается, и глушить его не нужно. */
  const [waitedForData] = useState(() => !ready);

  return { revealed: ready || capReached, waitedForData };
}
