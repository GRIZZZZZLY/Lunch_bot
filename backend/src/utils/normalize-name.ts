/**
 * Ключ дедупликации пользовательских названий: магазинов группы
 * (`GroupStore.normalizedName`) и товаров пользователя
 * (`UserItemPreset.normalizedName`).
 *
 * Функция одна на обе таблицы намеренно. Разъехавшиеся правила означали бы, что
 * «Пятёрочка» и «пятерочка» — один магазин, но «Молоко» и «молоко» — два разных
 * товара, и объяснить это пользователю нечем.
 *
 * `ё` → `е` здесь не косметика: в русских названиях букву пишут через раз, и без
 * этой замены справочник копил бы пары-близнецы. Обратной операции нет и не
 * нужно — исходное написание всегда лежит рядом в поле `name`, а нормализованное
 * значение наружу не показывается.
 */
export function normalizeName(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/\s+/g, ' ');
}
