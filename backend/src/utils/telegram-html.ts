/**
 * Экранирование для сообщений Telegram с `parse_mode: 'HTML'`.
 *
 * Экранируются ровно три символа — этого и требует Telegram: в его HTML-режиме
 * нет ни атрибутов, ни кавычек, поэтому `"` и `'` трогать не нужно, а `&amp;`
 * обязан идти первым, иначе он съест собственные подстановки.
 *
 * Зачем отдельный модуль: копий было две, дословно одинаковых, и одна из них
 * была объявлена СТРЕЛКОЙ ВНУТРИ МЕТОДА (feedback.service.ts) — такую не
 * находит ни grep по `function escapeHtml`, ни knip. Третий, кому понадобится
 * экранирование, написал бы третью.
 *
 * Цена ошибки не косметическая: имя пользователя или название блюда с `<`
 * или `&` даёт от Telegram `400 Bad Request: can't parse entities`, и
 * сообщение не доставляется вообще.
 */
export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/**
 * То же, но для `parse_mode: 'Markdown'` — legacy-разметки Telegram.
 *
 * Отказ ровно такой же и по той же причине: блюдо с именем `Соус_острый` или
 * `Плов *акция*` даёт `400 Bad Request: can't parse entities`, и сообщение не
 * доходит. Сообщений на Markdown в проекте БОЛЬШЕ, чем на HTML, а
 * экранирования в них не было вовсе.
 *
 * Экранируются четыре символа, которые legacy-Markdown считает разметкой:
 * `_`, `*`, `` ` ``, `[`. Больше — нельзя: legacy-режим не понимает
 * `\`-экранирование прочих символов и отдаёт их вместе с обратным слэшем.
 *
 * Применять ТОЛЬКО к подставляемым данным, не ко всему сообщению: сами
 * `*жирный*` и `_курсив_` в шаблонах должны остаться разметкой.
 */
export function escapeMarkdown(text: string): string {
  return text.replace(/([_*`[])/g, '\\$1');
}
