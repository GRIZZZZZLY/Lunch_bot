/**
 * Правило домена: какие блюда имеет в виду набор голосов.
 *
 * `Vote.menuItemId` — nullable, потому что голос может быть не за блюдо
 * («принесу своё», «пропускаю»). Везде, где из `groupBy(['menuItemId'])`
 * строится выборка блюд, такие голоса ОТБРАСЫВАЮТСЯ.
 *
 * Одна конкретная форма этого правила — «отобрать id блюд» — была записана
 * четыре раза: в poll.service.ts и трижды в vote.service.ts. Теперь она здесь.
 *
 * Честная оговорка: сама проверка `menuItemId !== null` в vote.service.ts
 * встречается и в другой форме — фильтрация СТРОК с сохранением остальных
 * полей (`vote.service.ts:982`, `:1149`). Их сюда не тащили осознанно: у них
 * другой тип результата, а порог из задачи 14.2 — три вхождения, не два.
 * То есть смена трактовки `null` всё ещё потребует пройтись по vote.service.ts
 * глазами; этот модуль убирает четыре правки из шести, а не все.
 *
 * Сам `findMany` сюда НЕ переехал сознательно: в трёх местах у него разные
 * `select`, и объединение их в одну «универсальную» выборку заставило бы
 * тянуть лишние поля ради единообразия.
 */

/**
 * Любая строка с `menuItemId`: и результат
 * `prisma.vote.groupBy({ by: ['menuItemId', ...] })`, и сам `Vote`.
 */
export interface VoteMenuItemRow {
  menuItemId: number | null;
}

/** Идентификаторы блюд из групп голосов; голоса не за блюдо отброшены. */
export function menuItemIdsFromVoteGroups(rows: VoteMenuItemRow[]): number[] {
  return rows
    .map(row => row.menuItemId)
    .filter((menuItemId): menuItemId is number => menuItemId !== null);
}
