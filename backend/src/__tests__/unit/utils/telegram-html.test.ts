/**
 * Экранирование для `parse_mode: 'HTML'`. Проверяется на русском тексте
 * намеренно: обе снятые копии применялись именно к именам пользователей и
 * названиям блюд, а не к латинице из примеров.
 *
 * Цена ошибки — не косметика: неэкранированный `<` или `&` даёт от Telegram
 * `400 Bad Request: can't parse entities`, и сообщение не доставляется вовсе.
 */
import { escapeHtml, escapeMarkdown } from '../../../utils/telegram-html';

describe('escapeHtml', () => {
  it.each([
    ['Соус <острый>', 'Соус &lt;острый&gt;'],
    ['Чай & кофе', 'Чай &amp; кофе'],
    ['<b>Игорь</b>', '&lt;b&gt;Игорь&lt;/b&gt;'],
    ['5 > 3 и 2 < 4', '5 &gt; 3 и 2 &lt; 4'],
  ])('%s → %s', (input, expected) => {
    expect(escapeHtml(input)).toBe(expected);
  });

  /* Порядок замен важен: если `&` экранировать не первым, он съест
     собственные подстановки и `<` превратится в `&amp;lt;`. */
  it('амперсанд экранируется первым, а не после угловых скобок', () => {
    expect(escapeHtml('<')).toBe('&lt;');
    expect(escapeHtml('&lt;')).toBe('&amp;lt;');
  });

  it('обычный русский текст не меняется', () => {
    expect(escapeHtml('Плов с бараниной, 350 ₽')).toBe(
      'Плов с бараниной, 350 ₽'
    );
  });

  /* Кавычки в HTML-режиме Telegram экранировать не нужно: атрибутов там нет,
     и лишняя замена испортила бы читаемый текст. */
  it('кавычки и апострофы остаются как есть', () => {
    expect(escapeHtml('Салат «Цезарь» и d\'Artagnan')).toBe(
      'Салат «Цезарь» и d\'Artagnan'
    );
  });

  it('пустая строка не ломает функцию', () => {
    expect(escapeHtml('')).toBe('');
  });
});

/**
 * Markdown ломается тем же способом, что HTML, и сообщений на Markdown в
 * проекте больше. Экранирования в них не было вовсе — блюдо `Соус_острый`
 * или `Плов *акция*` роняло доставку с `can't parse entities`.
 */
describe('escapeMarkdown', () => {
  it.each([
    ['Соус_острый', 'Соус\\_острый'],
    ['Плов *акция*', 'Плов \\*акция\\*'],
    ['Код `тут`', 'Код \\`тут\\`'],
    ['Меню [новое]', 'Меню \\[новое]'],
    ['_*`[', '\\_\\*\\`\\['],
  ])('%s → %s', (input, expected) => {
    expect(escapeMarkdown(input)).toBe(expected);
  });

  it('обычный русский текст не меняется', () => {
    expect(escapeMarkdown('Плов с бараниной, 350 ₽')).toBe(
      'Плов с бараниной, 350 ₽'
    );
  });

  /* Закрывающая `]` намеренно НЕ экранируется: в legacy-Markdown разметку
     начинает `[`, а одинокая `]` безопасна. Экранировать её обратным слэшем
     нельзя — legacy-режим не понимает `\` перед произвольным символом и
     отдаст слэш в текст. */
  it('одинокая закрывающая скобка остаётся как есть', () => {
    expect(escapeMarkdown('300 ₽]')).toBe('300 ₽]');
  });

  it('угловые скобки не трогает — это забота HTML-режима', () => {
    expect(escapeMarkdown('Соус <острый>')).toBe('Соус <острый>');
  });

  it('пустая строка не ломает функцию', () => {
    expect(escapeMarkdown('')).toBe('');
  });
});
