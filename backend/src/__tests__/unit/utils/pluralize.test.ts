/**
 * Плюрализация — таблица значений на границах, где русские правила ломаются:
 * 11–14 берут форму «много» вопреки последней цифре, а 111 и 112 — вопреки
 * первому впечатлению — ведут себя как 11 и 12.
 *
 * Домен функции — целые неотрицательные: количество голосов, людей, дней.
 */
import { pluralForm, pluralize } from '../../../utils/pluralize';

describe('pluralForm', () => {
  it.each([
    [0, 'голосов'],
    [1, 'голос'],
    [2, 'голоса'],
    [4, 'голоса'],
    [5, 'голосов'],
    [11, 'голосов'],
    [12, 'голосов'],
    [14, 'голосов'],
    [21, 'голос'],
    [111, 'голосов'],
    [112, 'голосов'],
    [115, 'голосов'],
    [22, 'голоса'],
    [100, 'голосов'],
    [101, 'голос'],
  ])('%i → %s', (n, expected) => {
    expect(pluralForm(n, 'голос', 'голоса', 'голосов')).toBe(expected);
  });
});

describe('pluralize', () => {
  it('подставляет число перед формой', () => {
    expect(pluralize(3, 'блюдо', 'блюда', 'блюд')).toBe('3 блюда');
    expect(pluralize(1, 'блюдо', 'блюда', 'блюд')).toBe('1 блюдо');
    expect(pluralize(11, 'блюдо', 'блюда', 'блюд')).toBe('11 блюд');
  });
});
