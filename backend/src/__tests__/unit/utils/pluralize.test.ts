/**
 * Плюрализация — таблица значений на границах, где русские правила ломаются:
 * 11–14 берут форму «много» вопреки последней цифре, а 111 и 112 — вопреки
 * первому впечатлению — ведут себя как 11 и 12.
 *
 * Вторая половина файла закрепляет ЭКВИВАЛЕНТНОСТЬ четырёх снятых реализаций
 * общей функции. Это не украшение: замена четырёх копий на одну обоснована
 * ровно тем, что они дают одинаковый ответ, и проверить это надо было ДО
 * замены, а не после. Копии оставлены здесь дословно как эталон сравнения —
 * но тел два, а не четыре: три из четырёх были побайтово одинаковы.
 */
import { pluralForm, pluralize } from '../../../utils/pluralize';

/**
 * Границы, названные в плане задачи 14.1.
 *
 * Домен функции — ЦЕЛЫЕ НЕОТРИЦАТЕЛЬНЫЕ: во всех вызовах это количество
 * голосов, людей, дней или недель. Дробные значения сюда не входят
 * намеренно, и на них общая функция расходится со снятыми копиями:
 * `pluralForm(2.5, …)` даёт «few», а `getVotesWord(2.5)` давал «many».
 * Расхождение безопасно ровно потому, что дробного количества голосов не
 * бывает; закреплять его тестом значило бы придать ему смысл, которого нет.
 */
const BOUNDARY_NUMBERS = [0, 1, 2, 4, 5, 11, 12, 14, 21, 111];

describe('pluralForm', () => {
  it.each([
    [0, 'голосов'],
    [1, 'голос'],
    [2, 'голоса'],
    [4, 'голоса'],
    [5, 'голосов'],
    [11, 'голосов'],
    [12, 'голосов'],
    [14, 'голосов'],
    [21, 'голос'],
    [111, 'голосов'],
    [112, 'голосов'],
    [115, 'голосов'],
    [22, 'голоса'],
    [100, 'голосов'],
    [101, 'голос'],
  ])('%i → %s', (n, expected) => {
    expect(pluralForm(n, 'голос', 'голоса', 'голосов')).toBe(expected);
  });
});

describe('pluralize', () => {
  it('подставляет число перед формой', () => {
    expect(pluralize(3, 'блюдо', 'блюда', 'блюд')).toBe('3 блюда');
    expect(pluralize(1, 'блюдо', 'блюда', 'блюд')).toBe('1 блюдо');
    expect(pluralize(11, 'блюдо', 'блюда', 'блюд')).toBe('11 блюд');
  });
});

/* ── Эталоны: реализации, снятые задачей 14.1 ────────────────────────────── */

/**
 * Одно тело на ТРИ снятые копии: `getPluralForm` в
 * bot/keyboards/poll.keyboard.ts, его дословный близнец в
 * services/notification.service.ts и `pluralize` в jobs/debt-reminder.job.ts.
 * Все три были побайтово одинаковы с точностью до имени и переносов строк —
 * держать здесь три идентичных функции значило бы делать вид, что они разные.
 *
 * Имя в debt-reminder.job.ts было отдельной ловушкой: `pluralize`, как на
 * фронте, но возвращало ФОРМУ, а не «число + форма». Подставить новый общий
 * `pluralize` под старое имя означало бы удвоить число в сообщениях о долгах.
 */
function legacyGetPluralForm(
  count: number,
  one: string,
  few: string,
  many: string
): string {
  if (count % 10 === 1 && count % 100 !== 11) return one;
  if ([2, 3, 4].includes(count % 10) && ![12, 13, 14].includes(count % 100)) {
    return few;
  }
  return many;
}

/** Была в services/poll.service.extensions.ts, умела только слово «голос». */
function legacyGetVotesWord(count: number): string {
  const lastDigit = count % 10;
  const lastTwoDigits = count % 100;

  if (lastTwoDigits >= 11 && lastTwoDigits <= 19) {
    return 'голосов';
  }
  if (lastDigit === 1) {
    return 'голос';
  }
  if (lastDigit >= 2 && lastDigit <= 4) {
    return 'голоса';
  }
  return 'голосов';
}

describe('снятые реализации давали тот же ответ', () => {
  /* Диапазон шире границ из плана: 0..130 покрывает обе «сотенные» аномалии
     (11–14 и 111–114) и обычные десятки между ними. */
  const RANGE = Array.from({ length: 131 }, (_, i) => i);

  it.each(BOUNDARY_NUMBERS)(
    'на границе %i совпадают обе снятые реализации',
    n => {
      const shared = pluralForm(n, 'голос', 'голоса', 'голосов');
      expect(legacyGetPluralForm(n, 'голос', 'голоса', 'голосов')).toBe(shared);
      expect(legacyGetVotesWord(n)).toBe(shared);
    }
  );

  it('на всём диапазоне 0..130 расхождений нет', () => {
    const mismatches = RANGE.filter(n => {
      const shared = pluralForm(n, 'голос', 'голоса', 'голосов');
      return (
        legacyGetPluralForm(n, 'голос', 'голоса', 'голосов') !== shared ||
        legacyGetVotesWord(n) !== shared
      );
    });

    expect(mismatches).toEqual([]);
  });

  /* getVotesWord обрабатывал 11–19 отдельной ветвью — план требовал убедиться,
     что общая функция делает то же. Делает: для 15–19 последняя цифра и так
     даёт «много», так что отдельная ветвь была избыточной, а не отличающейся. */
  it.each([11, 12, 13, 14, 15, 16, 17, 18, 19])(
    'отдельная ветвь getVotesWord для %i была избыточной, а не другой',
    n => {
      expect(pluralForm(n, 'голос', 'голоса', 'голосов')).toBe('голосов');
      expect(legacyGetVotesWord(n)).toBe('голосов');
    }
  );

  it('слова для «человек» тоже совпадают — одна из форм повторяется', () => {
    for (const n of BOUNDARY_NUMBERS) {
      expect(pluralForm(n, 'человек', 'человека', 'человек')).toBe(
        legacyGetPluralForm(n, 'человек', 'человека', 'человек')
      );
    }
  });
});
